/** Pure helpers for the sms-hook Edge Function (no Deno globals, so Vitest can test them). */

/** Supabase shows the secret as "v1,whsec_<base64>"; standardwebhooks wants the base64 part. */
export function hookSecret(raw: string): string {
  return raw.trim().replace(/^v1,/, "").replace(/^whsec_/, "")
}

export function maskPhone(e164: string): string {
  const d = e164.replace(/\D/g, "").slice(-10)
  return d.length === 10 ? `+91 ${d.slice(0, 2)}•••••${d.slice(7)}` : "•••"
}

/**
 * MSG91 OTP API v5 (verify at Gate G3 against docs.msg91.com):
 * POST https://control.msg91.com/api/v5/otp?template_id=…&mobile=91XXXXXXXXXX&otp=123456  header authkey
 * The OTP is generated by Supabase and passed through; MSG91 only delivers it on the DLT template.
 */
export function msg91Request(env: { MSG91_AUTH_KEY: string; MSG91_TEMPLATE_ID: string }, phone: string, otp: string) {
  if (!/^\d{4,8}$/.test(otp)) throw new Error("invalid otp")
  const mobile = phone.replace(/\D/g, "")
  if (!/^91[6-9]\d{9}$/.test(mobile)) throw new Error("only Indian mobile numbers are supported")
  const url = new URL("https://control.msg91.com/api/v5/otp")
  url.searchParams.set("template_id", env.MSG91_TEMPLATE_ID)
  url.searchParams.set("mobile", mobile)
  url.searchParams.set("otp", otp)
  return { url: url.toString(), init: { method: "POST", headers: { authkey: env.MSG91_AUTH_KEY, "Content-Type": "application/json" }, body: "{}" } }
}

export function hookError(message: string, status = 400) {
  // Supabase Auth surfaces error.message to the client.
  return new Response(JSON.stringify({ error: { http_code: status, message } }), { status, headers: { "Content-Type": "application/json" } })
}
